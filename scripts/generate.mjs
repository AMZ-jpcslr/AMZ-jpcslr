import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {hero, heading, card, about, divider} from './notebook-art.mjs';

const root = new URL('../', import.meta.url);
if (process.argv.slice(2).some(a => a !== '--check')) throw Error('Use --check or no arguments.');
const check = process.argv.includes('--check');
const p = JSON.parse(await readFile(new URL('profile.json', root), 'utf8'));
const e = s => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const site = new URL(p.portfolio);
if (site.protocol !== 'https:' || site.username || site.password || !/^[a-z0-9-]{1,39}$/i.test(p.username)) throw Error('Invalid URL or username.');
function text(v) { if (typeof v !== 'string' || !v.trim() || /[\u0000-\u001f]/u.test(v)) throw Error('Invalid profile text'); }
[p.name, p.nameEn, p.about, p.affiliation, ...p.skills].forEach(text);
if ([...p.nameEn].length > 25) throw Error('Header name too long.');
if (!Array.isArray(p.tools) || !p.tools.length) throw Error('No tools.');
for (const tool of p.tools) { text(tool.name); text(tool.label); if (!(tool.months > 0)) throw Error('Invalid tool months'); }
if (!p.projects.length) throw Error('No projects.');
const seen = new Set();
for (const pr of p.projects) {
  if (!/^[a-z0-9-]+$/.test(pr.slug) || seen.has(pr.slug) || !/^[a-z0-9][a-z0-9_.-]*$/i.test(pr.repository)) throw Error('Invalid project');
  seen.add(pr.slug); [pr.title, pr.description, pr.category].forEach(text);
}

// 画像は 昼/夜 × PC/スマホ の4種類を生成し、<picture> で切り替えます。
const art = new Map();
const variants = (name, make) => {
  for (const theme of ['day', 'night']) for (const mobile of [false, true]) {
    if (mobile && name === 'divider') continue;
    art.set('assets/notebook/' + name + (theme === 'night' ? '-night' : '') + (mobile ? '-mobile' : '') + '.svg', make({theme, mobile}));
  }
};
variants('hero', o => hero(p, o));
variants('heading-message', o => heading('MESSAGE', 'Message', '自己紹介', o));
variants('heading-works', o => heading('WORKS', 'Works', '作品一覧', o));
variants('heading-about', o => heading('ABOUT', 'About Me', '経歴とスキル', o));
p.projects.forEach((pr, i) => variants('work-' + pr.slug, o => card(pr, i, o)));
variants('about', o => about(p, o));
variants('divider', o => divider(o));

const version = '?v=' + createHash('sha256').update([...art.values()].join('')).digest('hex').slice(0, 12);
const a = (url, label) => '<a href="' + e(url) + '">' + label + '</a>';
const repo = pr => 'https://github.com/' + p.username + '/' + pr.repository;
const detail = pr => new URL('projects/' + pr.slug + '/', site).href;
const pic = (name, alt, {mobile = true} = {}) => {
  const f = s => 'assets/notebook/' + name + s + '.svg' + version;
  return '<picture>\n' +
    (mobile ? '<source media="(prefers-color-scheme: dark) and (max-width: 540px)" srcset="' + f('-night-mobile') + '">\n' : '') +
    (mobile ? '<source media="(max-width: 540px)" srcset="' + f('-mobile') + '">\n' : '') +
    '<source media="(prefers-color-scheme: dark)" srcset="' + f('-night') + '">\n' +
    '<img src="' + f('') + '" width="100%" alt="' + e(alt) + '">\n</picture>';
};

const content = [
  a(site.href, pic('hero', p.name + ' / ' + p.nameEn + '。紙と真鍮と歯車でできた、からくり修理屋の工房。懐中時計を修理するイラスト。')),
  '<p align="center">' + a(site.href, 'Portfolio ↗') + '　·　' + a(new URL('about/', site).href, 'About me ↗') + '　·　' + a('https://github.com/' + p.username + '?tab=repositories', 'Repositories ↗') + '</p>',
  pic('heading-message', 'Message / 自己紹介'),
  '<p>' + e(p.about) + '</p>',
  pic('heading-works', 'Works / 作品一覧'),
  '<p>カードを押すとGitHubのリポジトリへ移動します。制作の背景はポートフォリオの各作品ページで読めます。</p>',
  p.projects.map((pr, i) => a(repo(pr), pic('work-' + pr.slug, 'No. ' + String(i + 1).padStart(2, '0') + ' ' + pr.category + '：' + pr.title + '。' + pr.description)) +
    '\n<p align="right"><sub>' + a(repo(pr), 'コード ↗') + '　·　' + a(detail(pr), '制作の背景 ↗') + '</sub></p>').join('\n\n'),
  pic('heading-about', 'About Me / 経歴とスキル'),
  a(new URL('about/', site).href, pic('about', p.nameEn + ' / ' + p.name + '、' + p.affiliation + '。ツール使用歴：' + p.tools.map(x => x.name + ' ' + x.label).join('、') + '。スキル：' + p.skills.join('、') + '。')),
  pic('divider', '歯車とレールの区切り', {mobile: false}),
  '<p align="center"><sub>AMZ / PORTFOLIO</sub><br>' + a(site.href, 'ポートフォリオを見る ↗') + '</p>'
].join('\n\n') + '\n';

const template = await readFile(new URL('scripts/preview-template.html', root), 'utf8');
const outputs = new Map([
  ['README.md', '<!-- Generated by scripts/generate.mjs from profile.json. -->\n\n' + content],
  ['preview.html', template.replace('<!-- USERNAME -->', () => e(p.username)).replace('<!-- CONTENT -->', () => content)],
  ...art
]);
for (const [name, value] of outputs) {
  const url = new URL(name, root);
  if (check) {
    const current = await readFile(url, 'utf8').catch(() => '');
    if (current.replace(/\r\n/g, '\n') !== value.replace(/\r\n/g, '\n')) throw Error(name + ' needs rebuilding');
  } else { await mkdir(new URL('.', url), {recursive: true}); await writeFile(url, value, 'utf8'); }
}
console.log((check ? 'Verified' : 'Generated') + ' ' + outputs.size + ' files; ' + p.projects.length + ' project links. Offline build.');
