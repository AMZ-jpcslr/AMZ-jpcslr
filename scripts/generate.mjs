import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {hero,divider} from './clockwork-art.mjs';

const root=new URL('../',import.meta.url);
if(process.argv.slice(2).some(a=>a!=='--check')) throw Error('Use --check or no arguments.');
const check=process.argv.includes('--check');
const p=JSON.parse(await readFile(new URL('profile.json',root),'utf8'));
const e=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const site=new URL(p.portfolio);
if(site.protocol!=='https:'||site.username||site.password||!/^[a-z0-9-]{1,39}$/i.test(p.username))throw Error('Invalid URL or username.');
function text(v){if(typeof v!=='string'||!v.trim()||/[\u0000-\u001f]/u.test(v))throw Error('Invalid profile text');}
[p.name,p.nameEn,p.about,p.affiliation,...p.skills].forEach(text);
if([...p.nameEn].length>25)throw Error('Header name too long.');
if(!p.projects.length)throw Error('No projects.');
const seen=new Set();
for(const pr of p.projects){
 if(!/^[a-z0-9-]+$/.test(pr.slug)||seen.has(pr.slug)||!/^[a-z0-9][a-z0-9_.-]*$/i.test(pr.repository))throw Error('Invalid project');
 seen.add(pr.slug);[pr.title,pr.description,pr.category].forEach(text);
}
const a=(url,label)=>'<a href="'+e(url)+'">'+label+'</a>';
const repo=pr=>'https://github.com/'+p.username+'/'+pr.repository;
const detail=pr=>new URL('projects/'+pr.slug+'/',site).href;
const version='?v='+createHash('sha256').update(hero(p)).digest('hex').slice(0,12);
const image=(name,alt)=>'<img src="assets/clockwork/'+name+'.svg'+version+'" width="100%" alt="'+e(alt)+'">';
const heroTag='<picture>\n<source media="(prefers-reduced-motion: reduce) and (max-width: 540px)" srcset="assets/clockwork/hero-static-mobile.svg'+version+'">\n<source media="(prefers-reduced-motion: reduce)" srcset="assets/clockwork/hero-static.svg'+version+'">\n<source media="(max-width: 540px)" srcset="assets/clockwork/hero-mobile.svg'+version+'">\n'+image('hero',p.name+' / '+p.nameEn+' — Clockwork Atelier。真鍮の歯車と緑の光を重ねた工房の紋章。')+'\n</picture>';
const group=(items,start)=>'<table>\n'+items.map((pr,i)=>'<tr>\n<td>\n<sub>'+String(start+i+1).padStart(2,'0')+' / '+e(pr.category)+'</sub><br>\n<strong>'+a(repo(pr),e(pr.title))+'</strong><br>\n'+e(pr.description)+'<br>\n'+a(repo(pr),'コード ↗')+'　·　'+a(detail(pr),'制作の背景 ↗')+'\n</td>\n</tr>').join('\n')+'\n</table>';
const content=[
a(site.href,heroTag),
'<p align="center">'+a(site.href,'Portfolio ↗')+'　·　'+a(new URL('about/',site).href,'About me ↗')+'　·　'+a('https://github.com/'+p.username+'?tab=repositories','Repositories ↗')+'</p>',
'<h2>01 / 自己紹介</h2>\n<p><b>'+e(p.name)+'</b>　/　'+e(p.affiliation)+'</p>\n<p>'+e(p.about)+'</p>\n<p>'+p.skills.map(s=>'<code>'+e(s)+'</code>').join(' ')+'</p>',
image('divider','歯車の区切り'),
'<h2>02 / アプリ・Bot</h2>\n<p>作品名からソースコードへ移動できます。</p>',
group(p.projects.slice(0,5),0),
'<h2>03 / 研究・検証</h2>\n<p>AIの行動判断、通信の可視化、ロボットサッカーの位置評価に取り組んでいます。</p>',
group(p.projects.slice(5),5),
image('divider','歯車の区切り'),
'<p align="center"><sub>AMZ / CLOCKWORK ATELIER</sub><br>'+a(site.href,'ポートフォリオを見る ↗')+'</p>'
].join('\n\n')+'\n';
const template=await readFile(new URL('scripts/preview-template.html',root),'utf8');
const outputs=new Map([
 ['README.md','<!-- Generated by scripts/generate.mjs from profile.json. -->\n\n'+content],
 ['preview.html',template.replace('<!-- USERNAME -->',()=>e(p.username)).replace('<!-- CONTENT -->',()=>content)],
 ['assets/clockwork/hero-static.svg',hero(p,false,false)],['assets/clockwork/hero-static-mobile.svg',hero(p,true,false)],['assets/clockwork/hero.svg',hero(p)],['assets/clockwork/hero-mobile.svg',hero(p,true)],['assets/clockwork/divider.svg',divider()]
]);
for(const [name,value]of outputs){
 const url=new URL(name,root);
 if(check){
 const current=await readFile(url,'utf8');
 if(current.replace(/\r\n/g,'\n')!==value.replace(/\r\n/g,'\n'))throw Error(name+' needs rebuilding');
 }else{await mkdir(new URL('.',url),{recursive:true});await writeFile(url,value,'utf8');}
}
console.log((check?'Verified':'Generated')+' '+outputs.size+' files; '+p.projects.length+' project links. Offline build.');
